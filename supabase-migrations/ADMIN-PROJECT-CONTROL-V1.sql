-- Project Control v1: Admin-only project workspace and append-only history
create table if not exists public.admin_project_workspaces_v1 (
 id uuid primary key default gen_random_uuid(),
 project_key text not null unique check(length(btrim(project_key)) between 2 and 80),
 title text not null check(length(btrim(title)) between 2 and 180),
 description text not null default '',
 status text not null default 'active' check(status in ('active','paused','completed','archived')),
 current_phase text not null default 'planning',
 next_action text not null default '',
 state jsonb not null default '{}'::jsonb check(jsonb_typeof(state)='object'),
 created_by uuid references auth.users(id) on delete set null,
 updated_by uuid references auth.users(id) on delete set null,
 created_at timestamptz not null default now(),
 updated_at timestamptz not null default now()
);
create table if not exists public.admin_project_events_v1 (
 id bigint generated by default as identity primary key,
 project_id uuid not null references public.admin_project_workspaces_v1(id) on delete cascade,
 event_type text not null check(event_type in ('checkpoint','audit','requirement','issue','decision','note','phase_change')),
 checkpoint_code text,
 title text not null check(length(btrim(title)) between 2 and 200),
 details text not null default '',
 result_status text not null default 'recorded' check(result_status in ('recorded','verified','pending','blocked','resolved')),
 evidence jsonb not null default '{}'::jsonb check(jsonb_typeof(evidence)='object'),
 created_by uuid references auth.users(id) on delete set null,
 created_at timestamptz not null default now()
);
create index if not exists idx_admin_project_events_project_created on public.admin_project_events_v1(project_id,created_at desc);
alter table public.admin_project_workspaces_v1 enable row level security;
alter table public.admin_project_events_v1 enable row level security;
create policy admin_project_workspaces_admin_select on public.admin_project_workspaces_v1 for select to authenticated using(exists(select 1 from public.profiles p where p.id=(select auth.uid()) and p.is_admin=true));
create policy admin_project_workspaces_admin_insert on public.admin_project_workspaces_v1 for insert to authenticated with check(exists(select 1 from public.profiles p where p.id=(select auth.uid()) and p.is_admin=true));
create policy admin_project_workspaces_admin_update on public.admin_project_workspaces_v1 for update to authenticated using(exists(select 1 from public.profiles p where p.id=(select auth.uid()) and p.is_admin=true)) with check(exists(select 1 from public.profiles p where p.id=(select auth.uid()) and p.is_admin=true));
create policy admin_project_events_admin_select on public.admin_project_events_v1 for select to authenticated using(exists(select 1 from public.profiles p where p.id=(select auth.uid()) and p.is_admin=true));
create policy admin_project_events_admin_insert on public.admin_project_events_v1 for insert to authenticated with check(exists(select 1 from public.profiles p where p.id=(select auth.uid()) and p.is_admin=true));
grant select,insert,update on public.admin_project_workspaces_v1 to authenticated;
grant select,insert on public.admin_project_events_v1 to authenticated;
grant usage,select on sequence public.admin_project_events_v1_id_seq to authenticated;
